function FooterLink({
  href,
  label,
  children,
}: {
  href: string;
  label: string;
  children: React.ReactNode;
}) {
  return (
    <a
      href={href}
      target="_blank"
      rel="noopener noreferrer"
      aria-label={`${label} — opens in new tab`}
      className="transition-opacity focus:outline-none"
      style={{ color: "rgba(245,240,232,0.5)" }}
      onMouseEnter={(e) =>
        ((e.currentTarget as HTMLElement).style.color = "var(--gold)")
      }
      onMouseLeave={(e) =>
        ((e.currentTarget as HTMLElement).style.color = "rgba(245,240,232,0.5)")
      }
      onFocus={(e) => {
        (e.currentTarget as HTMLElement).style.color = "var(--gold)";
        (e.currentTarget as HTMLElement).style.outline = "2px solid var(--gold)";
        (e.currentTarget as HTMLElement).style.outlineOffset = "3px";
      }}
      onBlur={(e) => {
        (e.currentTarget as HTMLElement).style.color = "rgba(245,240,232,0.5)";
        (e.currentTarget as HTMLElement).style.outline = "none";
      }}
    >
      {children}
    </a>
  );
}

